"""Build the dataset files: paraphrases, split and the data report.

Run: python -m codetrust.tasks.build
Task validation (slow, runs every reference and vulnerable solution) is a separate step:
python -m codetrust.tasks.validate. The report includes its result when results/task_validation.json
exists.
"""

import json
import statistics
from collections import Counter

from codetrust.config import SEED
from codetrust.paths import DATA_DIR, RESULTS_DIR
from codetrust.tasks.loader import load_tasks
from codetrust.tasks.paraphrase import AXES, build_paraphrases, check_paraphrases
from codetrust.tasks.splits import make_split


def write_jsonl(path, rows):
    path.write_text(
        "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8"
    )


def build_report(tasks, rows, split, validation) -> str:
    families = Counter(t.family for t in tasks)
    cwe = {t.family: t.cwe for t in tasks}
    words = [len(r["prompt"].split()) for r in rows]
    by_axis = {a: [len(r["prompt"].split()) for r in rows if r["axis"] == a] for a in AXES}
    n_function = sum(1 for t in tasks if "create_app" not in t.entry)
    lines = [
        "# Data report",
        "",
        f"Generated by `python -m codetrust.tasks.build` (seed {SEED}).",
        "",
        "## Counts",
        "",
        f"- Tasks: {len(tasks)} in {len(families)} vulnerability families",
        f"- Prompts: {len(rows)} ({len(AXES)} wordings per task)",
        f"- Planned generations per model: {len(rows)}; with 4 models: {len(rows) * 4}",
        f"- Split by task: {sum(v == 'dev' for v in split.values())} dev, "
        f"{sum(v == 'test' for v in split.values())} test",
        "",
        "## Tasks per family",
        "",
        "| Family | CWE | Tasks | Dev | Test |",
        "|---|---|---|---|---|",
    ]
    for family in sorted(families):
        dev = sum(1 for t in tasks if t.family == family and split[t.id] == "dev")
        lines.append(
            f"| {family} | {cwe[family]} | {families[family]} | {dev} | {families[family] - dev} |"
        )
    lines += [
        "",
        "## Prompt length (words)",
        "",
        f"All prompts: min {min(words)}, median {statistics.median(words):.0f}, max {max(words)}.",
        "",
        "| Wording axis | Median words |",
        "|---|---|",
    ]
    for axis in AXES:
        lines.append(f"| {axis} | {statistics.median(by_axis[axis]):.0f} |")
    lines += ["", "## Sample records", ""]
    sample = next(t for t in tasks if t.id == "sqli_find_user")
    for row in [r for r in rows if r["task_id"] == sample.id][:10:3]:
        lines += [f"### `{row['id']}` ({row['axis']})", "", "```text", row["prompt"], "```", ""]
    lines += ["## Task validation", ""]
    if validation is None:
        lines.append("Not run yet: `python -m codetrust.tasks.validate`.")
    else:
        bad = [v for v in validation if v["problems"]]
        ref_ok = sum(
            v["ref_correct"]["failed"] + v["ref_security"]["failed"] == 0 for v in validation
        )
        detects = sum(
            v["vuln_correct"]["failed"] == 0 and v["vuln_security"]["failed"] > 0
            for v in validation
        )
        lines += [
            f"- Tasks checked: {len(validation)}",
            f"- Reference solution passes correctness and security tests: {ref_ok}",
            "- Vulnerable solution passes correctness but fails security tests (so the security "
            f"test can detect the flaw): {detects}",
            f"- Tasks with problems: {len(bad)}",
        ]
        lines += [f"  - {v['id']}: {'; '.join(v['problems'])}" for v in bad]
    lines += [
        "",
        "## Quality problems found",
        "",
        "- **Hints in contracts.** Tests need exact function names and data, so some contracts "
        "give away part of the answer: environment variable names (hard-coded secrets tasks), "
        "the allowed redirect host, the header names for the access-control tasks, and "
        '"any other value sorts by id" in `sqli_sorted_items`. This probably makes models look '
        "safer than with fully open prompts. Reported as a limitation in Step 6.",
        "- **Templated wordings.** The ten wordings are made from fixed templates around one "
        "contract, so they differ in framing, tone and noise but not in how the requirement is "
        "explained. They measure sensitivity to framing, not to rewrites of the requirement.",
        f"- **Function-level tasks.** {n_function} of {len(tasks)} tasks are single functions "
        "rather than Flask apps, because functions can be tested without a running server. Real "
        "code has more context.",
        "- **Python only.** No JavaScript tasks in the core set.",
        "- **Test strictness.** Security tests accept an exception as a safe outcome for most "
        "tasks; a few (e.g. `sqli_find_user`) require the safe return value. Both choices were "
        "checked against the vulnerable solutions only, not against a wide range of safe ones.",
        "- **Public benchmarks.** None were downloaded or copied. See the README for licences.",
        "",
    ]
    return "\n".join(lines)


def main():
    tasks = load_tasks()
    rows = build_paraphrases(tasks)
    problems = check_paraphrases(tasks, rows)
    if problems:
        raise SystemExit("paraphrase problems:\n" + "\n".join(problems))
    split = make_split(tasks)
    write_jsonl(DATA_DIR / "paraphrases.jsonl", rows)
    (DATA_DIR / "splits.json").write_text(json.dumps(split, indent=2) + "\n", encoding="utf-8")
    validation_path = RESULTS_DIR / "task_validation.json"
    validation = (
        json.loads(validation_path.read_text(encoding="utf-8"))
        if validation_path.exists()
        else None
    )
    RESULTS_DIR.mkdir(exist_ok=True)
    (RESULTS_DIR / "data_report.md").write_text(
        build_report(tasks, rows, split, validation), encoding="utf-8"
    )
    print(f"{len(tasks)} tasks, {len(rows)} prompts, split {Counter(split.values())}")


if __name__ == "__main__":
    main()
